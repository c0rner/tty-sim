pub const READER_BUFFER_SIZE: usize = 8 * 1024;
const LIFECYCLE_POLL_INTERVAL: Duration = Duration::from_millis(10);

/// Focused outbound presentation contract consumed by automation workflows.
pub trait PresentationApi: Send + Sync {
    /// Ingests output from the child process.
    ///
    /// # Errors
    ///
    /// Returns a presentation error if processing or forwarding output fails.
    fn accept_child_output(&self, bytes: &[u8]) -> Result<Vec<u8>, PresentationError>;

    /// Ingests presentation output generated by script commands.
    ///
    /// # Errors
    ///
    /// Returns a presentation error if emitting generated bytes fails.
    fn emit_presentation(&self, bytes: &[u8]) -> Result<(), PresentationError>;

    /// Installs a presentation-only masking rule.
    ///
    /// # Errors
    ///
    /// Returns a presentation error if installing the rule fails.
    fn install_mask(&self, rule: &MaskRule) -> Result<(), PresentationError>;

    /// Clears received expectation history while preserving presentation and stream state.
    ///
    /// # Errors
    ///
    /// Returns a presentation error if output failed or history cannot be cleared.
    fn clear_history(&self) -> Result<(), PresentationError>;

    /// Blocks until the pattern appears in raw output or timeout expires.
    ///
    /// # Errors
    ///
    /// Returns an expectation error on timeout, EOF, or output failure.
    fn wait_for_expectation(
        &self,
        pattern: &[u8],
        timeout: Duration,
    ) -> Result<(), ExpectationError>;

    /// Inspects the coordinator for asynchronous background failures.
    ///
    /// # Errors
    ///
    /// Returns a presentation error if inspecting failure state fails.
    fn failure(&self) -> Result<Option<Arc<OutputFailure>>, PresentationError>;

    /// Records an asynchronous reader thread failure.
    ///
    /// # Errors
    ///
    /// Returns a presentation error if storing the failure fails.
    fn record_reader_failure(
        &self,
        source: io::Error,
    ) -> Result<Arc<OutputFailure>, PresentationError>;

    /// Concludes presentation and flushes remaining buffers.
    ///
    /// # Errors
    ///
    /// Returns a presentation error if flushing final output fails.
    fn finish(&self) -> Result<(), PresentationError>;
}

impl<P: PresentationApi> PresentationApi for Arc<P> {
    fn accept_child_output(&self, bytes: &[u8]) -> Result<Vec<u8>, PresentationError> {
        (**self).accept_child_output(bytes)
    }

    fn emit_presentation(&self, bytes: &[u8]) -> Result<(), PresentationError> {
        (**self).emit_presentation(bytes)
    }

    fn install_mask(&self, rule: &MaskRule) -> Result<(), PresentationError> {
        (**self).install_mask(rule)
    }

    fn wait_for_expectation(
        &self,
        pattern: &[u8],
        timeout: Duration,
    ) -> Result<(), ExpectationError> {
        (**self).wait_for_expectation(pattern, timeout)
    }

    fn clear_history(&self) -> Result<(), PresentationError> {
        (**self).clear_history()
    }

    fn failure(&self) -> Result<Option<Arc<OutputFailure>>, PresentationError> {
        (**self).failure()
    }

    fn record_reader_failure(
        &self,
        source: io::Error,
    ) -> Result<Arc<OutputFailure>, PresentationError> {
        (**self).record_reader_failure(source)
    }

    fn finish(&self) -> Result<(), PresentationError> {
        (**self).finish()
    }
}

/// Outbound terminal contract combining I/O, process control, and lifecycle operations.
pub trait TerminalSession: ChildHandle + Write + Send {
    /// Resizes the running terminal.
    ///
    /// # Errors
    ///
    /// Returns an I/O error if resizing fails.
    fn resize(&self, size: TerminalSize) -> io::Result<()>;

    /// Closes the terminal control channel.
    ///
    /// # Errors
    ///
    /// Returns an I/O error if closing fails.
    fn close(&mut self) -> io::Result<()>;

    /// Drops the terminal input channel.
    fn drop_input(&mut self);

    /// Joins the background reader thread.
    ///
    /// # Errors
    ///
    /// Returns a cleanup failure if the reader thread panicked.
    fn join_reader(&mut self) -> Result<(), CleanupFailure>;
}

/// Active terminal handle managing input sharing, child handle, control, and reader thread.
pub struct ActiveTerminal<I, C, T> {
    input: Option<Arc<Mutex<I>>>,
    child: Option<C>,
    control: Option<T>,
    reader: Option<JoinHandle<()>>,
}

impl<I, C, T> ActiveTerminal<I, C, T> {
    pub const fn new(input: Arc<Mutex<I>>, child: C, control: T, reader: JoinHandle<()>) -> Self {
        Self {
            input: Some(input),
            child: Some(child),
            control: Some(control),
            reader: Some(reader),
        }
    }

    #[cfg(test)]
    pub fn replace_reader_for_test(&mut self, reader: JoinHandle<()>) {
        if let Some(old) = self.reader.take() {
            let _ = old.join();
        }
        self.reader = Some(reader);
    }
}

impl<I: Write + Send, C: ChildHandle, T: TerminalControl> Write for ActiveTerminal<I, C, T> {
    fn write(&mut self, buffer: &[u8]) -> io::Result<usize> {
        let input = self
            .input
            .as_ref()
            .ok_or_else(|| io::Error::other("terminal input is closed"))?;
        let mut guard = input
            .lock()
            .map_err(|_| io::Error::other("terminal input state is poisoned"))?;
        guard.write(buffer)
    }

    fn flush(&mut self) -> io::Result<()> {
        let input = self
            .input
            .as_ref()
            .ok_or_else(|| io::Error::other("terminal input is closed"))?;
        let mut guard = input
            .lock()
            .map_err(|_| io::Error::other("terminal input state is poisoned"))?;
        guard.flush()
    }
}

impl<I: Write + Send, C: ChildHandle, T: TerminalControl> ChildHandle for ActiveTerminal<I, C, T> {
    fn try_wait(&mut self) -> io::Result<Option<ChildExitStatus>> {
        self.child
            .as_mut()
            .ok_or_else(|| io::Error::other("terminal child is unavailable"))?
            .try_wait()
    }

    fn wait(&mut self) -> io::Result<ChildExitStatus> {
        let mut child = self
            .child
            .take()
            .ok_or_else(|| io::Error::other("terminal child is unavailable"))?;
        child.wait()
    }

    fn process_group_is_alive(&self) -> io::Result<bool> {
        let Some(child) = self.child.as_ref() else {
            return Ok(false);
        };
        child.process_group_is_alive()
    }

    fn terminate_group(&mut self) -> io::Result<()> {
        let Some(child) = self.child.as_mut() else {
            return Ok(());
        };
        child.terminate_group()
    }

    fn kill_group(&mut self) -> io::Result<()> {
        let Some(child) = self.child.as_mut() else {
            return Ok(());
        };
        child.kill_group()
    }
}

impl<I: Write + Send, C: ChildHandle, T: TerminalControl> TerminalSession
    for ActiveTerminal<I, C, T>
{
    fn resize(&self, size: TerminalSize) -> io::Result<()> {
        self.control
            .as_ref()
            .ok_or_else(|| io::Error::other("terminal session is complete"))?
            .resize(size)
    }

    fn close(&mut self) -> io::Result<()> {
        let Some(control) = self.control.as_ref() else {
            return Ok(());
        };
        control.close()
    }

    fn drop_input(&mut self) {
        self.input = None;
    }

    fn join_reader(&mut self) -> Result<(), CleanupFailure> {
        if let Some(reader) = self.reader.take() {
            if reader.join().is_err() {
                return Err(CleanupFailure::ReaderPanicked);
            }
        }
        Ok(())
    }
}

/// Spawns the background reader thread connecting the PTY output to the presentation pipeline.
pub fn spawn_reader<O, I, P>(
    mut reader: O,
    input: Arc<Mutex<I>>,
    presentation: Arc<P>,
) -> JoinHandle<()>
where
    O: Read + Send + 'static,
    I: Write + Send + 'static,
    P: PresentationApi + 'static,
{
    thread::spawn(move || {
        let mut buffer = [0; READER_BUFFER_SIZE];
        loop {
            match reader.read(&mut buffer) {
                Ok(0) => {
                    trace!("PTY output reader reached EOF");
                    let _ = presentation.finish();
                    break;
                }
                Ok(count) => {
                    let bytes = &buffer[..count];
                    match presentation.accept_child_output(bytes) {
                        Ok(responses) => {
                            if !responses.is_empty() {
                                let write_res = input
                                    .lock()
                                    .map_err(|_| {
                                        io::Error::other("terminal input state is poisoned")
                                    })
                                    .and_then(|mut guard| {
                                        guard.write_all(&responses).and_then(|()| guard.flush())
                                    });
                                if let Err(source) = write_res {
                                    let _ = presentation.record_reader_failure(source);
                                    break;
                                }
                            }
                        }
                        Err(_) => break,
                    }
                }
                Err(source) => {
                    debug!(error = %source, "PTY output reader failed");
                    let _ = presentation.record_reader_failure(source);
                    break;
                }
            }
        }
    })
}

/// Generic automation session workflow.
///
/// Orchestrates command execution and lifecycle management over generic terminal,
/// presentation, sleeper, and delay contracts.
pub struct Session<T: TerminalSession, P: PresentationApi, S: Sleeper, R: DelaySource> {
    terminal: Option<T>,
    presentation: P,
    sleeper: S,
    delay_source: R,
    typing_range: TypingRange,
    history_capacity: usize,
    natural_exit_grace: Duration,
    termination_grace: Duration,
    child_status: Option<ChildExitStatus>,
}

impl<T: TerminalSession, P: PresentationApi, S: Sleeper, R: DelaySource> Session<T, P, S, R> {
    pub fn new(
        terminal: T,
        presentation: P,
        sleeper: S,
        delay_source: R,
        history_capacity: usize,
        natural_exit_grace: Duration,
        termination_grace: Duration,
    ) -> Self {
        Self {
            terminal: Some(terminal),
            presentation,
            sleeper,
            delay_source,
            typing_range: TypingRange::default(),
            history_capacity,
            natural_exit_grace,
            termination_grace,
            child_status: None,
        }
    }

    #[cfg(test)]
    pub const fn terminal_mut(&mut self) -> Option<&mut T> {
        self.terminal.as_mut()
    }

    /// Validates and executes a slice of commands sequentially.
    ///
    /// # Errors
    ///
    /// Returns an error if pre-flight validation fails, input write fails,
    /// presentation fails, an expectation fails, or the child exits early.
    pub fn execute(&mut self, commands: &[Command]) -> Result<(), ExecutionError> {
        let indexed_commands = commands
            .iter()
            .enumerate()
            .map(|(index, command)| (command, CommandContext::Index(index + 1)))
            .collect::<Vec<_>>();

        for (command, context) in &indexed_commands {
            validate_command(command, self.history_capacity, *context)?;
        }

        for (command, context) in &indexed_commands {
            debug!(
                ?context,
                command = command_name(command),
                "starting script command"
            );
            self.check_boundary(*context)?;
            self.execute_command(command, *context)?;
            self.check_boundary(*context)?;
            debug!(
                ?context,
                command = command_name(command),
                "completed script command"
            );
        }

        Ok(())
    }

    /// Resizes the running terminal.
    ///
    /// # Errors
    ///
    /// Returns a terminal-control error if resizing fails.
    pub fn resize(&self, size: TerminalSize) -> Result<(), TerminalError> {
        self.terminal
            .as_ref()
            .ok_or_else(|| TerminalError::Control {
                operation: "resize closed terminal",
                source: io::Error::other("terminal session is complete"),
            })?
            .resize(size)
            .map_err(|source| TerminalError::Control {
                operation: "resize",
                source,
            })
    }

    /// Waits without timeout for natural child completion and drains output.
    ///
    /// # Errors
    ///
    /// Returns every cleanup failure observed during shutdown.
    pub fn wait_for_exit(mut self) -> Result<Completion, CleanupError> {
        self.drop_input();
        let mut failures = Vec::new();
        self.wait_for_child(&mut failures);
        if self.child_status.is_some() {
            self.join_reader(&mut failures);
            self.close_terminal(&mut failures);
        } else {
            self.close_terminal(&mut failures);
            self.join_reader(&mut failures);
        }
        self.record_output_failure(&mut failures);
        let completion = self.completion(TerminationOutcome::Natural, failures);
        self.terminal = None;
        completion
    }

    /// Grants configured natural exit grace before bounded TERM/KILL escalation.
    ///
    /// # Errors
    ///
    /// Returns every lifecycle and cleanup failure observed during shutdown.
    pub fn finish(mut self) -> Result<Completion, CleanupError> {
        self.drop_input();
        let mut failures = Vec::new();
        let outcome =
            match self.wait_for_group(self.natural_exit_grace, "natural exit", &mut failures) {
                GroupWait::Stopped => TerminationOutcome::Natural,
                GroupWait::Alive => self.terminate_group(&mut failures),
            };
        self.finish_resources(outcome, failures)
    }

    /// Immediately initiates bounded TERM/KILL escalation without waiting for natural exit.
    ///
    /// # Errors
    ///
    /// Returns every lifecycle and cleanup failure observed during termination.
    pub fn terminate(mut self) -> Result<Completion, CleanupError> {
        self.drop_input();
        let mut failures = Vec::new();
        let outcome = if self.group_is_alive(&mut failures) {
            self.terminate_group(&mut failures)
        } else {
            TerminationOutcome::Natural
        };
        self.finish_resources(outcome, failures)
    }

    fn execute_command(
        &mut self,
        command: &Command,
        context: CommandContext,
    ) -> Result<(), ExecutionError> {
        match command {
            Command::Type(text) => {
                for character in text.chars() {
                    let mut encoded = [0; 4];
                    self.write_and_flush(character.encode_utf8(&mut encoded).as_bytes(), context)?;
                    let delay = self
                        .delay_source
                        .sample_inclusive(self.typing_range.minimum(), self.typing_range.maximum());
                    self.sleeper.sleep(delay);
                }
                Ok(())
            }
            Command::Typing(range) => {
                self.typing_range = *range;
                Ok(())
            }
            Command::Key(bytes) | Command::Send(bytes) => self.write_and_flush(bytes, context),
            Command::Show(bytes) => self
                .presentation
                .emit_presentation(bytes)
                .map_err(|error| map_presentation_error(error, context)),
            Command::Wait(duration) => {
                self.sleeper.sleep(*duration);
                Ok(())
            }
            Command::Drain(duration) => {
                self.presentation
                    .clear_history()
                    .map_err(|error| map_presentation_error(error, context))?;
                if !duration.is_zero() {
                    self.sleeper.sleep(*duration);
                    self.presentation
                        .clear_history()
                        .map_err(|error| map_presentation_error(error, context))?;
                }
                Ok(())
            }
            Command::Expect { pattern, timeout } => self
                .presentation
                .wait_for_expectation(pattern, *timeout)
                .map_err(|error| map_expectation_error(error, context)),
            Command::Mask(rule) => self
                .presentation
                .install_mask(rule)
                .map_err(|error| map_presentation_error(error, context)),
            Command::Simulate { command, output } => {
                for character in command.chars() {
                    let mut encoded = [0; 4];
                    self.presentation
                        .emit_presentation(character.encode_utf8(&mut encoded).as_bytes())
                        .map_err(|error| map_presentation_error(error, context))?;
                    let delay = self
                        .delay_source
                        .sample_inclusive(self.typing_range.minimum(), self.typing_range.maximum());
                    self.sleeper.sleep(delay);
                }
                self.presentation
                    .emit_presentation(output)
                    .map_err(|error| map_presentation_error(error, context))
            }
        }
    }

    fn write_and_flush(
        &mut self,
        bytes: &[u8],
        context: CommandContext,
    ) -> Result<(), ExecutionError> {
        let terminal = self
            .terminal
            .as_mut()
            .ok_or_else(|| ExecutionError::Input {
                context,
                source: io::Error::other("terminal input is closed"),
            })?;
        terminal
            .write_all(bytes)
            .and_then(|()| terminal.flush())
            .map_err(|source| ExecutionError::Input { context, source })
    }

    fn check_boundary(&mut self, context: CommandContext) -> Result<(), ExecutionError> {
        if let Some(source) = self
            .presentation
            .failure()
            .map_err(|error| map_presentation_error(error, context))?
        {
            return Err(ExecutionError::Output { context, source });
        }
        let terminal = self
            .terminal
            .as_mut()
            .ok_or_else(|| ExecutionError::Input {
                context,
                source: io::Error::other("terminal child is unavailable"),
            })?;
        match terminal.try_wait() {
            Ok(Some(status)) => {
                self.child_status = Some(status.clone());
                Err(ExecutionError::EarlyChildExit { context, status })
            }
            Ok(None) => Ok(()),
            Err(source) => Err(ExecutionError::Input { context, source }),
        }
    }

    fn finish_resources(
        &mut self,
        outcome: TerminationOutcome,
        mut failures: Vec<CleanupFailure>,
    ) -> Result<Completion, CleanupError> {
        if matches!(outcome, TerminationOutcome::Natural) {
            self.join_reader(&mut failures);
            self.close_terminal(&mut failures);
        } else {
            self.close_terminal(&mut failures);
            self.join_reader(&mut failures);
        }
        self.wait_for_child(&mut failures);
        self.record_output_failure(&mut failures);
        let completion = self.completion(outcome, failures);
        self.terminal = None;
        completion
    }

    fn terminate_group(&mut self, failures: &mut Vec<CleanupFailure>) -> TerminationOutcome {
        if let Some(terminal) = self.terminal.as_mut() {
            if let Err(source) = terminal.terminate_group() {
                failures.push(operation_failure("send SIGTERM", source));
            }
        }
        match self.wait_for_group(self.termination_grace, "SIGTERM", failures) {
            GroupWait::Stopped => TerminationOutcome::Sigterm,
            GroupWait::Alive => {
                if let Some(terminal) = self.terminal.as_mut() {
                    if let Err(source) = terminal.kill_group() {
                        failures.push(operation_failure("send SIGKILL", source));
                    }
                }
                TerminationOutcome::Sigkill
            }
        }
    }

    fn wait_for_group(
        &mut self,
        grace: Duration,
        operation: &'static str,
        failures: &mut Vec<CleanupFailure>,
    ) -> GroupWait {
        let Some(deadline) = Instant::now().checked_add(grace) else {
            failures.push(CleanupFailure::DeadlineOverflow { operation });
            return GroupWait::Alive;
        };
        loop {
            self.observe_child(failures);
            if !self.group_is_alive(failures) {
                return GroupWait::Stopped;
            }
            let Some(remaining) = deadline.checked_duration_since(Instant::now()) else {
                return GroupWait::Alive;
            };
            if remaining.is_zero() {
                return GroupWait::Alive;
            }
            self.sleeper.sleep(remaining.min(LIFECYCLE_POLL_INTERVAL));
        }
    }

    fn group_is_alive(&self, failures: &mut Vec<CleanupFailure>) -> bool {
        let Some(terminal) = self.terminal.as_ref() else {
            return false;
        };
        match terminal.process_group_is_alive() {
            Ok(alive) => alive,
            Err(source) => {
                failures.push(operation_failure("check process group", source));
                true
            }
        }
    }

    fn observe_child(&mut self, failures: &mut Vec<CleanupFailure>) {
        if self.child_status.is_some() {
            return;
        }
        let Some(terminal) = self.terminal.as_mut() else {
            return;
        };
        match terminal.try_wait() {
            Ok(status) => self.child_status = status,
            Err(source) => failures.push(operation_failure("poll child", source)),
        }
    }

    fn wait_for_child(&mut self, failures: &mut Vec<CleanupFailure>) {
        if self.child_status.is_none() {
            if let Some(terminal) = self.terminal.as_mut() {
                match terminal.wait() {
                    Ok(status) => self.child_status = Some(status),
                    Err(source) => failures.push(operation_failure("reap child", source)),
                }
            }
        }
    }

    fn drop_input(&mut self) {
        if let Some(terminal) = self.terminal.as_mut() {
            terminal.drop_input();
        }
    }

    fn close_terminal(&mut self, failures: &mut Vec<CleanupFailure>) {
        if let Some(terminal) = self.terminal.as_mut() {
            if let Err(source) = terminal.close() {
                failures.push(operation_failure("close terminal", source));
            }
        }
    }

    fn join_reader(&mut self, failures: &mut Vec<CleanupFailure>) {
        if let Some(terminal) = self.terminal.as_mut() {
            if let Err(failure) = terminal.join_reader() {
                failures.push(failure);
            }
        }
    }

    fn record_output_failure(&self, failures: &mut Vec<CleanupFailure>) {
        match self.presentation.failure() {
            Ok(Some(source)) => failures.push(CleanupFailure::Output { source }),
            Ok(None) => {}
            Err(PresentationError::Synchronization(source)) => {
                failures.push(CleanupFailure::Synchronization(
                    crate::automation::SynchronizationError {
                        resource: source.resource,
                    },
                ));
            }
            Err(PresentationError::OffsetOverflow) => failures.push(operation_failure(
                "inspect output",
                io::Error::other("raw output stream offset overflowed"),
            )),
            Err(err) => failures.push(operation_failure(
                "inspect output",
                io::Error::other(err.to_string()),
            )),
        }
    }

    fn completion(
        &mut self,
        outcome: TerminationOutcome,
        failures: Vec<CleanupFailure>,
    ) -> Result<Completion, CleanupError> {
        let status = self.child_status.take();
        match (failures.is_empty(), status) {
            (true, Some(status)) => Ok(Completion::new(status, outcome)),
            (_, None) => {
                let mut failures = failures;
                failures.push(operation_failure(
                    "collect child status",
                    io::Error::other("child exit status is unavailable"),
                ));
                Err(CleanupError::new(failures))
            }
            (false, Some(_)) => Err(CleanupError::new(failures)),
        }
    }
}

impl<T: TerminalSession, P: PresentationApi, S: Sleeper, R: DelaySource> Drop
    for Session<T, P, S, R>
{
    fn drop(&mut self) {
        if self.terminal.is_none() {
            return;
        }
        self.drop_input();
        let mut ignored = Vec::new();
        if self.group_is_alive(&mut ignored) {
            let _ = self.terminate_group(&mut ignored);
        }
        self.close_terminal(&mut ignored);
        self.join_reader(&mut ignored);
        self.wait_for_child(&mut ignored);
        self.terminal = None;
    }
}

enum GroupWait {
    Stopped,
    Alive,
}

const fn operation_failure(operation: &'static str, source: io::Error) -> CleanupFailure {
    CleanupFailure::Operation { operation, source }
}

const fn command_name(command: &Command) -> &'static str {
    match command {
        Command::Type(_) => "type",
        Command::Typing(_) => "typing",
        Command::Key(_) => "key",
        Command::Send(_) => "send",
        Command::Show(_) => "show",
        Command::Wait(_) => "wait",
        Command::Drain(_) => "drain",
        Command::Expect { .. } => "expect",
        Command::Mask(_) => "mask",
        Command::Simulate { .. } => "simulate",
    }
}

/// Validates a command against policy and limits before execution.
///
/// # Errors
///
/// Returns an execution error if the command violates schema or buffer limits.
pub fn validate_command(
    command: &Command,
    capacity: usize,
    context: CommandContext,
) -> Result<(), ExecutionError> {
    let error: Option<CommandConfigurationError> = match command {
        Command::Expect { pattern, .. } if pattern.is_empty() => {
            Some(crate::presentation::ConfigurationError::EmptyExpectPattern.into())
        }
        Command::Expect { pattern, .. } if pattern.len() > capacity => Some(
            crate::presentation::ConfigurationError::ExpectPatternTooLarge {
                pattern: pattern.len(),
                capacity,
            }
            .into(),
        ),
        Command::Type(_)
        | Command::Typing(_)
        | Command::Key(_)
        | Command::Send(_)
        | Command::Show(_)
        | Command::Wait(_)
        | Command::Drain(_)
        | Command::Expect { .. }
        | Command::Mask(_)
        | Command::Simulate { .. } => None,
    };
    error.map_or(Ok(()), |source| {
        Err(ExecutionError::Configuration { context, source })
    })
}

fn map_expectation_error(error: ExpectationError, context: CommandContext) -> ExecutionError {
    match error {
        ExpectationError::Configuration(source) => ExecutionError::Configuration {
            context,
            source: source.into(),
        },
        ExpectationError::Timeout => ExecutionError::ExpectTimeout { context },
        ExpectationError::Eof => ExecutionError::ExpectEof { context },
        ExpectationError::Output { source } => ExecutionError::Output { context, source },
        ExpectationError::Synchronization(source) => ExecutionError::Synchronization {
            context,
            source: crate::automation::SynchronizationError {
                resource: source.resource,
            },
        },
        ExpectationError::AlreadyActive
        | ExpectationError::DeadlineOverflow
        | ExpectationError::OffsetOverflow => internal_output_error(error.to_string(), context),
    }
}

fn map_presentation_error(error: PresentationError, context: CommandContext) -> ExecutionError {
    match error {
        PresentationError::Configuration(source) => ExecutionError::Configuration {
            context,
            source: source.into(),
        },
        PresentationError::Output { source }
        | PresentationError::FailureRecording {
            failure: source, ..
        } => ExecutionError::Output { context, source },
        PresentationError::Synchronization(source) => ExecutionError::Synchronization {
            context,
            source: crate::automation::SynchronizationError {
                resource: source.resource,
            },
        },
        PresentationError::OffsetOverflow
        | PresentationError::Finished
        | PresentationError::ExpectationActive => internal_output_error(error.to_string(), context),
    }
}

fn internal_output_error(message: String, context: CommandContext) -> ExecutionError {
    ExecutionError::Output {
        context,
        source: Arc::new(OutputFailure::Reader(io::Error::other(message))),
    }
}

