    #[test]
    fn concurrent_child_and_generated_submissions_are_serialized_as_whole_slices() {
        const PRODUCERS: usize = 12;
        let callback_active = Arc::new(AtomicBool::new(false));
        let overlap = Arc::new(AtomicBool::new(false));
        let emissions = Arc::new(Mutex::new(Vec::new()));
        let sink = CallbackSink::from_io({
            let callback_active = Arc::clone(&callback_active);
            let overlap = Arc::clone(&overlap);
            let emissions = Arc::clone(&emissions);
            move |bytes| {
                if callback_active.swap(true, Ordering::SeqCst) {
                    overlap.store(true, Ordering::SeqCst);
                }
                thread::sleep(Duration::from_millis(2));
                emissions.lock().unwrap().push(bytes.to_vec());
                callback_active.store(false, Ordering::SeqCst);
                Ok(())
            }
        });
        let coordinator = Arc::new(OutputCoordinator::new(capacity(64), sink, &[]));
        let start = Arc::new(Barrier::new(PRODUCERS + 1));
        let mut producers = Vec::new();
        for index in 0..PRODUCERS {
            let coordinator = Arc::clone(&coordinator);
            let start = Arc::clone(&start);
            producers.push(thread::spawn(move || {
                let submission = [u8::try_from(index).unwrap(), 0xff];
                start.wait();
                if index % 2 == 0 {
                    coordinator.accept_child_output(&submission).map(|_| ())
                } else {
                    coordinator.emit_presentation(&submission)
                }
            }));
        }
        start.wait();
        for producer in producers {
            producer.join().unwrap().unwrap();
        }

        assert!(!overlap.load(Ordering::SeqCst));
        let mut actual = emissions.lock().unwrap().clone();
        actual.sort_unstable();
        let expected: Vec<Vec<u8>> = (0..PRODUCERS)
            .map(|index| vec![u8::try_from(index).unwrap(), 0xff])
            .collect();
        assert_eq!(actual, expected);
    }

